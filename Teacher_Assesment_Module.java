    private void jButton3ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton3ActionPerformed
String title = txtTitle.getText();
    String desc = jTextField1.getText(); // Description field
    String deadline = txtDeadline.getText();

    if (title.isEmpty() || desc.isEmpty() || deadline.isEmpty()) {
        JOptionPane.showMessageDialog(this, "সবগুলো ঘর পূরণ করুন!");
        return;
    }

    try {
        Connection conn = databaseconnect.connect();
        // নিশ্চিত করুন আপনার assignments টেবিলে task_description কলামটি আছে
        String sql = "INSERT INTO assignments (title, task_description, deadline) VALUES (?, ?, ?)";
        PreparedStatement pst = conn.prepareStatement(sql);
        pst.setString(1, title);
        pst.setString(2, desc);
        pst.setString(3, deadline); // Format: YYYY-MM-DD
        
        pst.executeUpdate();
        JOptionPane.showMessageDialog(this, "নতুন টাস্ক সফলভাবে যোগ হয়েছে!");
        
        // ইনপুট বক্স খালি করা
        txtTitle.setText("");
        jTextField1.setText("");
        txtDeadline.setText("");
        
        // নতুন টাস্ক যোগ করার পর সাবমিশন টেবিলটি রিফ্রেশ করা (ঐচ্ছিক)
        loadAllTasks();
        
    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, "Error: " + e.getMessage() + 
            "\nনিশ্চিত করুন Date ফরম্যাট YYYY-MM-DD এবং ডাটাবেসে task_description কলাম আছে।");
    }
        // TODO add your handling code here:
    }//GEN-LAST:event_jButton3ActionPerformed

