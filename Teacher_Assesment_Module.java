    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
    int row = table1.getSelectedRow();
    if (row == -1) {
        JOptionPane.showMessageDialog(this, "আগে টেবিল থেকে একটি সারি সিলেক্ট করুন!");
        return;
    }

    // টেবিলের ৩ নম্বর কলাম থেকে ডাটা নিচ্ছি (যেখানে file_path থাকার কথা)
    Object value = table1.getValueAt(row, 2); 
    
    if (value == null || value.toString().isEmpty()) {
        JOptionPane.showMessageDialog(this, "এই সারিতে কোনো ফাইল পাথ নেই!");
        return;
    }

    String path = value.toString();
    try {
        java.io.File file = new java.io.File(path);
        if (file.exists()) {
            java.awt.Desktop.getDesktop().open(file); 
        } else {
            // যদি এটি ফাইল পাথ না হয়ে সাধারণ বর্ণনা (Description) হয়
            JOptionPane.showMessageDialog(this, "এটি একটি বর্ণনা, কোনো ফাইল নয়। ফাইল দেখতে 'Submission View' এ যান।\nবর্ণনা: " + path);
        }
    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, "ফাইল ওপেন করা যাচ্ছে না: " + e.getMessage());
    }
  // TODO add your handling code here:
    }//GEN-LAST:event_jButton1ActionPerformed

